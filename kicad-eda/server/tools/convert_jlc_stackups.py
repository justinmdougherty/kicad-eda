"""Convert the JLCPCB stackup snapshot into server/data/fabs/jlcpcb_templates.json.

    python convert_jlc_stackups.py <normalised_json dir> <out.json>
                                   [--commit SHA] [--commit-date YYYY-MM-DD]

Input: the ``normalised_json`` directory of
https://github.com/gsuberland/jlcpcb_autogenerated_stackups (ADR D7.3 pins
commit 9c8b685, 2025-05-20: 577 templates). Its author released
``normalised_json`` into the public domain; ``raw_json`` is the property of
JLCPCB, so a path through a ``raw_json`` directory (or a file in the raw API
shape) is refused and nothing is written. JLC's private API is never called.

Output (schema ``kicad-eda/fab_templates@1``, one template per line, sorted,
byte-stable): ``{"schema", "fab": "jlcpcb", "attribution", "format", "count",
"templates": {id: {copper_layers, thickness_mm, outer_oz, inner_oz, jlc_name,
file, stack}}}``. A template id is the JLC name (``JLC04161H-7628``); the
order page's "no requirement" stackups (``NOREQ``, one per layer count /
thickness / copper weights) become ``NOREQ-<n>L-<t>mm-<outer>oz-<inner>oz``.
The stack lists, top to bottom, ``{"cu": mm, "oz": weight}`` and
``{"pp"|"core": material id, "c": construction, "t": mm, "snapshot_dk"}``;
consecutive dielectric plies form one dielectric layer.

Stdlib only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

SCHEMA = "kicad-eda/fab_templates@1"
REPOSITORY = "https://github.com/gsuberland/jlcpcb_autogenerated_stackups"
SNAPSHOT_COMMIT = "9c8b68507c27d454a585fcc424685ffafcc46e2d"
SNAPSHOT_DATE = "2025-05-20"
NOREQ = "NOREQ"
NAME_RE = re.compile(
    r"^jlcpcb_(\d+)L_([\d.]+)mm_outer([\d.]+)oz_inner([\d.]+)oz_([A-Za-z0-9._-]+)\.json$")
# snapshot (Manufacturer, Model) -> materials library id (server/data/materials)
MATERIAL_IDS = {
    ("Nan Ya Plastics", "NP-155F"): "nanya.np155f",
    ("SYTECH (Shengyi)", "S1000-2M"): "shengyi.s1000-2m",
}
ATTRIBUTION = {
    "repository": REPOSITORY,
    "path": "normalised_json",
    "author": "Graham Sutherland (gsuberland)",
    "license": ("normalised_json is released into the public domain by its author; raw_json is "
                "the property of JLCPCB (reference only) and is never converted or vendored"),
    "warning": ("auto-generated by the snapshot's author from JLCPCB's impedance-template data "
                "and not verified by JLCPCB; Dk values come from JLC's impedance calculator "
                "guide via the snapshot"),
    "converter": "server/tools/convert_jlc_stackups.py",
}
FORMAT = {
    "stack": ("top to bottom: {cu: thickness mm, oz} copper; {pp|core: material id, c: "
              "construction, t: thickness mm, snapshot_dk} dielectric plies; "
              "consecutive plies between two coppers form one dielectric layer"),
    "snapshot_dk": ("the snapshot's Dk, kept for provenance; presets do not copy it into "
                    "layers: the materials library resolves Dk (its JLC fab entries reproduce "
                    "these values, tests/test_fab_presets.py). The snapshot's loss tangents "
                    "(0.02 NP-155F, 0.018 S1000-2M) are its author's, not JLC's, and are "
                    "not kept: Df comes from the data sheets"),
}


def _num(x: Any) -> int | float:
    v = float(x)
    return int(v) if v.is_integer() else v


def _fmt(v: float) -> str:
    return f"{v:g}"


def template_id(layers: int, thickness: float, outer: float, inner: float, name: str) -> str:
    """The JLC template name, or NOREQ-<n>L-<t>mm-<outer>oz-<inner>oz."""
    if name != NOREQ:
        return name
    return f"{NOREQ}-{layers}L-{_fmt(thickness)}mm-{_fmt(outer)}oz-{_fmt(inner)}oz"


def refuse_raw(path: Path) -> None:
    """raw_json is JLCPCB's property: never read it."""
    if any("raw_json" in part.lower() for part in Path(path).resolve().parts):
        raise ValueError(f"{path}: raw_json is JLCPCB property and is never converted or "
                         "vendored; point the converter at normalised_json")


def _copper(fname: str, layer: dict) -> dict:
    try:
        return {"cu": round(float(layer["Thickness"]), 6), "oz": _num(layer["Weight"])}
    except (KeyError, TypeError, ValueError) as exc:
        raise ValueError(f"{fname}: copper layer without Thickness/Weight") from exc


def _ply(fname: str, layer: dict) -> dict:
    m = layer.get("Material")
    if not isinstance(m, dict):
        raise ValueError(f"{fname}: dielectric without Material (not normalised_json)")
    key = (m.get("Manufacturer"), m.get("Model"))
    mid = MATERIAL_IDS.get(key)
    if mid is None:
        raise ValueError(f"{fname}: unknown material {key[0]!r} / {key[1]!r}: map it in "
                         "MATERIAL_IDS and add it to the materials library")
    construction = str(m.get("Construction", "")).strip()
    if not construction:
        raise ValueError(f"{fname}: dielectric without Construction")
    return {"core" if m.get("IsCore") else "pp": mid,
            "c": "core" if construction.lower() == "core" else construction,
            "t": round(float(layer["Thickness"]), 6),
            "snapshot_dk": float(m["DielectricConstant"])}


def convert_file(path: Path) -> tuple[str, dict]:
    """One normalised_json stackup -> (template id, template)."""
    path = Path(path)
    match = NAME_RE.match(path.name)
    if not match:
        raise ValueError(f"{path.name}: not a jlcpcb_<n>L_<t>mm_outer<o>oz_inner<i>oz_<name> file")
    layers, thickness, outer, inner, name = match.groups()
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, list) or not data or not all(isinstance(x, dict) for x in data):
        raise ValueError(f"{path.name}: not a normalised_json stackup (expected a list of layers)")
    stack: list[dict] = []
    for layer in data:
        kind = layer.get("Type")
        if kind == "Copper":
            stack.append(_copper(path.name, layer))
        elif kind == "Dielectric":
            stack.append(_ply(path.name, layer))
        else:
            raise ValueError(f"{path.name}: unknown layer Type {kind!r} (not normalised_json)")
    n_cu = sum(1 for e in stack if "cu" in e)
    if "cu" not in stack[0] or "cu" not in stack[-1] or n_cu != int(layers):
        raise ValueError(f"{path.name}: expected {layers} copper layers, first and last copper")
    tid = template_id(int(layers), float(thickness), float(outer), float(inner), name)
    return tid, {"copper_layers": int(layers), "thickness_mm": _num(thickness),
                 "outer_oz": _num(outer), "inner_oz": _num(inner), "jlc_name": name,
                 "file": path.name, "stack": stack}


def convert_dir(src: str | Path, *, commit: str = SNAPSHOT_COMMIT,
                commit_date: str = SNAPSHOT_DATE) -> dict:
    """Every jlcpcb_*.json under ``src`` -> the jlcpcb_templates.json document."""
    src = Path(src)
    refuse_raw(src)
    if not src.is_dir():
        raise ValueError(f"{src}: not a directory")
    files = sorted(src.glob("jlcpcb_*.json"), key=lambda p: p.name)
    if not files:
        raise ValueError(f"no jlcpcb_*.json stackups under {src}")
    templates: dict[str, dict] = {}
    for path in files:
        tid, tpl = convert_file(path)
        if tid in templates:
            raise ValueError(f"duplicate template id {tid!r} ({templates[tid]['file']}, "
                             f"{path.name})")
        templates[tid] = tpl
    attribution = {**ATTRIBUTION, "commit": commit, "commit_date": commit_date}
    return {"schema": SCHEMA, "fab": "jlcpcb", "attribution": attribution, "format": FORMAT,
            "count": len(templates), "templates": dict(sorted(templates.items()))}


def dumps(doc: dict) -> str:
    """Byte-stable JSON text: header keys first, then one template per line."""
    lines = ["{"]
    for key in ("schema", "fab", "attribution", "format", "count"):
        lines.append(f"  {json.dumps(key)}: {json.dumps(doc[key], sort_keys=True)},")
    rows = [f"    {json.dumps(tid)}: {json.dumps(tpl)}" for tid, tpl in doc["templates"].items()]
    lines.append('  "templates": {')
    lines.append(",\n".join(rows))
    lines.append("  }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("normalised_json", help="the snapshot's normalised_json directory")
    ap.add_argument("out", help="output path (server/data/fabs/jlcpcb_templates.json)")
    ap.add_argument("--commit", default=SNAPSHOT_COMMIT, help="snapshot commit sha")
    ap.add_argument("--commit-date", default=SNAPSHOT_DATE, help="snapshot commit date")
    args = ap.parse_args(argv)
    try:
        doc = convert_dir(args.normalised_json, commit=args.commit, commit_date=args.commit_date)
        Path(args.out).write_text(dumps(doc), encoding="utf-8", newline="\n")
    except (OSError, ValueError, KeyError) as exc:
        print(f"convert_jlc_stackups: error: {exc}", file=sys.stderr)
        return 2
    print(f"wrote {doc['count']} templates to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
