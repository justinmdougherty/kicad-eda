def test_classify_loops_directly() -> None:
    outer = Loop(((0, 0, 0), (10, 0, 0), (10, 10, 0), (0, 10, 0)), ("a",))
    hole = Loop(((2, 2, 0), (4, 2, 0), (4, 4, 0), (2, 4, 0)), ("b",))
    far = Loop(((20, 20, 0), (21, 20, 0), (21, 21, 0)), ("c",))
    out = dxf_loops.classify_loops([hole, far, outer])
    assert out.outer is outer
    assert out.cutouts == (hole,)
    assert [(loop, why) for loop, why in out.stray] == [(far, "outside the outer outline")]
    with pytest.raises(DxfOutlineError, match="no closed loop"):
        dxf_loops.classify_loops([])
    flat = Loop(((0, 0, 0), (10, 0, 0), (20, 0, 0)), ("d",))
    with pytest.raises(DxfOutlineError, match="zero area"):
        dxf_loops.classify_loops([flat])


