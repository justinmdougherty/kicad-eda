"""Unit tests for server/tools/dxf_loops.py: chaining DXF pieces into closed
loops, gap and branch reports, duplicate removal and the outer / cutout split
(docs/ROADMAP_DECISIONS.md D2). Most cases go through dxf_io's reader with
DXFs generated by tests/fixtures/dxf_builders.py.
"""
from __future__ import annotations

import math
from pathlib import Path

import pytest

import dxf_io
import dxf_loops
from dxf_loops import DxfOutlineError, Loop, Piece
from fixtures.dxf_builders import new_doc, rect_lines, rect_poly, save


# --- chaining and gap errors -------------------------------------------------------
def test_gap_error_is_precise(tmp_path: Path) -> None:
    doc, msp = new_doc()
    lines = rect_lines(msp, gap=0.25)
    path = save(doc, tmp_path)
    with pytest.raises(DxfOutlineError) as info:
        dxf_io.read_board_outline(path)
    err = info.value
    msg = str(err)
    assert "1 gap" in msg and "0.250 mm" in msg
    assert "(0.250, 30.000)" in msg and "(0.000, 30.000)" in msg
    assert f"LINE #{lines[2].dxf.handle} end" in msg
    assert f"LINE #{lines[3].dxf.handle} start" in msg
    assert "tol >= 0.251 mm" in msg
    [gap] = err.gaps
    assert gap.distance == pytest.approx(0.25)
    # a wider tolerance bridges it
    assert dxf_io.read_board_outline(path, tol=0.3).size == pytest.approx((50, 30), abs=0.3)


def test_small_gap_within_default_tolerance_closes(tmp_path: Path) -> None:
    doc, msp = new_doc()
    rect_lines(msp, gap=0.005)
    res = dxf_io.read_board_outline(save(doc, tmp_path))
    assert res.outline.area == pytest.approx(1500, abs=0.2)


def test_every_gap_is_listed(tmp_path: Path) -> None:
    doc, msp = new_doc()
    msp.add_line((0, 0), (49.5, 0))                # gap 0.5 at (50, 0)
    msp.add_line((50, 0), (50, 30))
    msp.add_line((50, 30), (0, 30))
    msp.add_line((0, 29), (0, 0))                  # gap 1.0 at the top-left
    with pytest.raises(DxfOutlineError) as info:
        dxf_io.read_board_outline(save(doc, tmp_path))
    msg = str(info.value)
    assert "2 gaps" in msg
    assert sorted(round(g.distance, 3) for g in info.value.gaps) == [0.5, 1.0]
    # 1 mm is not export noise at a 0.01 mm join tolerance: no 'raise tol' advice
    assert "tol >=" not in msg
    assert "wider than 0.5 mm are not export noise" in msg


def test_missing_edge_is_an_open_path(tmp_path: Path) -> None:
    doc, msp = new_doc()
    lines = [msp.add_line((0, 0), (50, 0)), msp.add_line((50, 0), (50, 30)),
             msp.add_line((50, 30), (0, 30))]
    with pytest.raises(DxfOutlineError) as info:
        dxf_io.read_board_outline(save(doc, tmp_path))
    [gap] = info.value.gaps
    assert gap.distance == pytest.approx(30)
    assert set(gap.open_path) == {f"LINE #{e.dxf.handle}" for e in lines}
    msg = str(info.value)
    assert "1 open path " in msg and "(ends 30.000 mm apart)" in msg
    assert "draw the missing edge" in msg and "tol >=" not in msg


def test_stray_construction_line_is_an_open_path_not_a_gap(tmp_path: Path) -> None:
    doc, msp = new_doc()
    rect_poly(msp, 0, 0, 50, 30)
    stray = msp.add_line((10, 15), (40, 15))       # e.g. a Fusion construction line
    with pytest.raises(DxfOutlineError) as info:
        dxf_io.read_board_outline(save(doc, tmp_path))
    err, msg = info.value, str(info.value)
    assert (f"open path LINE #{stray.dxf.handle} from (10.000, 15.000) to (40.000, 15.000) "
            "(ends 30.000 mm apart) is not part of a closed loop") in msg
    assert "1 open path (1 closed loop(s) found" in msg
    assert "construction geometry" in msg and "layer=" in msg
    # widening the join tolerance to 30 mm would wreck the outline: never advised
    assert "tol >=" not in msg and "gap 30" not in msg
    [gap] = err.gaps
    assert gap.open_path == (f"LINE #{stray.dxf.handle}",)
    assert err.problems == (gap.describe(),)


def test_wide_gaps_between_two_stray_lines_get_no_tol_advice(tmp_path: Path) -> None:
    doc, msp = new_doc()
    rect_poly(msp, 0, 0, 50, 30)
    msp.add_line((10, 15), (40, 15))
    msp.add_line((10, 20), (40, 20))               # ends pair across the lines, 5 mm
    with pytest.raises(DxfOutlineError) as info:
        dxf_io.read_board_outline(save(doc, tmp_path))
    msg = str(info.value)
    assert [round(g.distance, 3) for g in info.value.gaps] == [5.0, 5.0]
    assert not any(g.open_path for g in info.value.gaps)
    assert "2 gaps" in msg and "tol >=" not in msg
    assert "not export noise" in msg and "construction geometry" in msg


@pytest.mark.parametrize(("gap", "tol", "advice"), [
    (0.4, 0.01, "tol >= 0.401 mm"),                # within max(50 x tol, 0.5 mm)
    (0.6, 0.01, None),                             # wider: an open path
    (0.6, 0.02, "tol >= 0.601 mm"),                # 50 x 0.02 = 1 mm of noise
])
def test_tol_advice_only_for_gaps_within_export_noise(tmp_path: Path, gap: float, tol: float,
                                                      advice: str | None) -> None:
    doc, msp = new_doc()
    rect_lines(msp, gap=gap)
    with pytest.raises(DxfOutlineError) as info:
        dxf_io.read_board_outline(save(doc, tmp_path), tol=tol)
    msg = str(info.value)
    if advice is None:
        assert "tol >=" not in msg and "open path" in msg
    else:
        assert advice in msg and "open path" not in msg
    assert dxf_loops.export_noise_mm(tol) == max(50 * tol, 0.5)


