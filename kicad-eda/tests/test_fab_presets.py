def summary(layers: list[dict]) -> list[tuple]:
    """Copper -> ('cu', thickness); dielectric -> (kind, ((material, construction, t), ...))."""
    out: list[tuple] = []
    for layer in layers:
        if layer["type"] == "copper":
            out.append(("cu", layer["thickness"]))
        else:
            plies = layer.get("plies") or [layer]
            out.append((layer["kind"], tuple((p["material"], p["construction"], p["thickness"])
                                              for p in plies)))
    return out


