def _cu(w: float, t: float) -> dict:
    return {"Type": "Copper", "Weight": w, "Thickness": t}


def _diel(model: str, construction: str, t: float, dk: float, core: bool) -> dict:
    maker = {"NP-155F": "Nan Ya Plastics", "S1000-2M": "SYTECH (Shengyi)"}.get(model, "Acme")
    return {"Type": "Dielectric", "Thickness": t, "Material": {
        "Manufacturer": maker, "Model": model, "Construction": construction,
        "NominalThickness": t, "ResinContent": 0 if core else 50, "DielectricConstant": dk,
        "LossTangent": 0.02, "GlassTransitionTemperature": 150, "ExpectedLayerCount": 0,
        "IsCore": core}}


def _snapshot(dirpath: Path) -> Path:
    src = dirpath / "normalised_json"
    src.mkdir(parents=True)
    std = [_cu(1, 0.035), _diel("NP-155F", "7628", 0.2104, 4.4, False), _cu(0.5, 0.0152),
           _diel("NP-155F", "Core", 1.065, 4.43, True), _cu(0.5, 0.0152),
           _diel("NP-155F", "7628", 0.2104, 4.4, False), _cu(1, 0.035)]
    (src / "jlcpcb_4L_1.6mm_outer1oz_inner0.5oz_JLC04161H-7628.json").write_text(
        json.dumps(std), encoding="utf-8")
    noreq = [_cu(1, 0.035), _diel("NP-155F", "2116", 0.127, 4.16, False),
             _diel("S1000-2M", "2313", 0.0964, 4.31, False), _cu(0.5, 0.0152),
             _diel("NP-155F", "Core", 1.3, 4.43, True), _cu(0.5, 0.0152),
             _diel("NP-155F", "2116", 0.127, 4.16, False), _cu(1, 0.035)]
    (src / "jlcpcb_4L_2mm_outer1oz_inner0.5oz_NOREQ.json").write_text(
        json.dumps(noreq), encoding="utf-8")
    return src


