def _check_child(proc: subprocess.CompletedProcess, fabs: fp.FabSet) -> dict:
    assert proc.returncode == 0, proc.stderr
    out = json.loads(proc.stdout.strip().splitlines()[-1])
    assert out["new"] == [] and out["tpl"] == "JLC06161H-2116" and out["n"] == 11
    assert out["probs"] == ["impedance_layer_count"] and out["dv"] == fabs.data_version
    return out


