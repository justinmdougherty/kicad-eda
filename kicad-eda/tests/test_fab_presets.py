def test_converter_cli_is_deterministic(tmp_path):
    src = _snapshot(tmp_path)
    outs = [tmp_path / "a.json", tmp_path / "b.json"]
    for out in outs:
        proc = subprocess.run([sys.executable, str(TOOLS / "convert_jlc_stackups.py"), str(src),
                               str(out)], capture_output=True, text=True,
                              stdin=subprocess.DEVNULL, timeout=LIVE_TIMEOUT_S,
                              encoding="utf-8", errors="replace")
        assert proc.returncode == 0, proc.stderr
    assert outs[0].read_bytes() == outs[1].read_bytes()
    loaded = json.loads(outs[0].read_text(encoding="utf-8"))
    assert loaded == conv.convert_dir(src)


def test_converter_refuses_raw_json(tmp_path):
    raw = tmp_path / "raw_json"
    raw.mkdir()
    (raw / "jlcpcb_4L_1.6mm_outer1oz_inner0.5oz_JLC04161H-7628.json").write_text(
        json.dumps({"code": 200, "data": {}}), encoding="utf-8")
    with pytest.raises(ValueError, match="raw_json"):
        conv.convert_dir(raw)
    proc = subprocess.run([sys.executable, str(TOOLS / "convert_jlc_stackups.py"), str(raw),
                           str(tmp_path / "o.json")], capture_output=True, text=True,
                          stdin=subprocess.DEVNULL, timeout=LIVE_TIMEOUT_S, encoding="utf-8",
                          errors="replace")
    assert proc.returncode == 2 and "raw_json" in proc.stderr
    assert not (tmp_path / "o.json").exists()
    # a raw-shaped file smuggled into another directory is refused too
    other = tmp_path / "elsewhere"
    other.mkdir()
    shutil.copy(raw / "jlcpcb_4L_1.6mm_outer1oz_inner0.5oz_JLC04161H-7628.json", other)
    with pytest.raises(ValueError, match="normalised"):
        conv.convert_dir(other)


