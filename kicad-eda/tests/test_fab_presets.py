def test_every_template_ply_resolves_to_the_snapshot_dk(fabs, lib):
    """The library's JLC fab entries reproduce the snapshot's Dk for all 577 templates."""
    checked = 0
    for name in fabs.templates("jlcpcb"):
        tpl = fabs.template("jlcpcb", name)
        for e in tpl["stack"]:
            if "cu" in e:
                continue
            material = e.get("pp") or e.get("core")
            assert material in lib, (name, material)
            rv = mat.resolve_dk(lib, material, freq_hz=1e9, policy="fab", fab="jlcpcb",
                                construction=e["c"], thickness_mm=e["t"])
            assert (rv.basis, rv.value) == ("fab", e["snapshot_dk"]), (name, e)
            checked += 1
    assert checked > 6000


