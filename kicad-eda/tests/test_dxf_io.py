def test_spline_flattened_within_tolerance(tmp_path: Path) -> None:
    doc, msp = new_doc()
    msp.add_line((0, 0), (40, 0))
    msp.add_line((40, 0), (40, 20))
    spline = msp.add_spline(fit_points=[(40, 20), (30, 24), (20, 25), (10, 24), (0, 20)])
    msp.add_line((0, 20), (0, 0))
    path = save(doc, tmp_path)
    res = dxf_io.read_board_outline(path)
    dense = [(p.x, p.y) for p in spline.construction_tool().approximate(2000)]
    h = res.size[1]                                # board y = h - DXF y (miny = 0)
    assert h == pytest.approx(max(y for _x, y in dense), abs=dxf_io.DEFAULT_CURVE_TOL_MM)
    ring = [(v[0], v[1]) for v in res.outline.vertices]
    worst = max(ring_dist((x, h - y), ring) for x, y in dense)
    assert worst <= dxf_io.DEFAULT_CURVE_TOL_MM + 1e-6
    coarse = dxf_io.read_board_outline(path, curve_tol=0.5)
    assert len(coarse.outline.vertices) < len(res.outline.vertices)


def test_wiggly_splines_stay_within_the_curve_tolerance(tmp_path: Path) -> None:
    # ezdxf's flattening overshoots its distance by ~5 % on curves like these
    rng = random.Random(7)
    for k in range(8):
        doc, msp = new_doc()
        fit = [(i * 8.0, 20 + rng.uniform(-6, 6)) for i in range(7)]
        msp.add_line((0, 0), (48, 0))
        msp.add_line((48, 0), fit[-1])
        spline = msp.add_spline(fit_points=fit[::-1])
        msp.add_line(fit[0], (0, 0))
        res = dxf_io.read_board_outline(save(doc, tmp_path, f"w{k}.dxf"), units="mm")
        ring = [(v[0], v[1]) for v in res.outline.vertices]
        x0 = res.datum[0]
        y0 = res.datum[1]                          # DXF (x, y) -> board (x + x0, y0 - y)
        dense = spline.construction_tool().approximate(3000)
        worst = max(ring_dist((p.x + x0, y0 - p.y), ring) for p in dense)
        assert worst <= dxf_io.DEFAULT_CURVE_TOL_MM, (k, worst)


