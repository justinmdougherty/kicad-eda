def test_ellipse_edge_and_ellipse_cutout(tmp_path: Path) -> None:
    doc, msp = new_doc()
    msp.add_line((0, 20), (0, 0))
    msp.add_line((0, 0), (40, 0))
    msp.add_line((40, 0), (40, 20))
    msp.add_ellipse((20, 20), (20, 0, 0), 0.25, 0, math.pi)        # top: half ellipse
    msp.add_ellipse((20, 8), (6, 0, 0), 0.5)                          # full ellipse hole
    res = dxf_io.read_board_outline(save(doc, tmp_path))
    tol = dxf_io.DEFAULT_CURVE_TOL_MM
    assert res.size == pytest.approx((40, 25), abs=tol)
    # inscribed chords lose at most (chord deviation x curve length) of area
    half = math.pi * math.sqrt((20 ** 2 + 5 ** 2) / 2)        # half-ellipse length
    assert 0 <= 800 + math.pi * 20 * 5 / 2 - res.outline.area <= tol * half
    [cut] = res.cutouts
    perimeter = 2 * math.pi * math.sqrt((6 ** 2 + 3 ** 2) / 2)
    assert 0 <= math.pi * 6 * 3 + cut.area <= tol * perimeter


